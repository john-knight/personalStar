/** 同一天两个人拿到同一题：按日期字符串算个固定的下标 */
function pickByDay(dayKey) {
  const s = String(dayKey || '');
  let h = 7;
  for (let i = 0; i < s.length; i++) {
    h = (h * 31 + s.charCodeAt(i)) % 1000003;
  }
  return DAILY_QUESTIONS[h % DAILY_QUESTIONS.length];
}

/** 本地日期键：2026-11-03 */
function todayKey(ts) {
  const d = ts ? new Date(ts) : new Date();
  const pad = (n) => (n < 10 ? `0${n}` : String(n));
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
}

function getQuestion(id) {
  for (let i = 0; i < DAILY_QUESTIONS.length; i++) {
    if (DAILY_QUESTIONS[i].id === id) {
      return DAILY_QUESTIONS[i];
    }
  }
  return null;
}

